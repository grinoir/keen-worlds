"""Keen and Mortimer tied up in the Megarocket (Keen Worlds): in Canmore's
Redemption, Craig flew them to Azura Astrid as captives -- "tied up in the
back, and they are not happy". So for the Canmore journey the aft bunk holds
the two of them bound with rope instead of Keen asleep. Drawn over the cabin's
own bunk art (kw_shiproom_art.py).

    python3 kwtools/kw_captives_art.py preview OUT.png
    python3 kwtools/kw_captives_art.py csource SRCDIR

A piece over the aft bunk (cabin map tiles 9-14, rows 19-23). Keen (green cap)
and Mortimer (dark hair, glasses) sit roped together on the bunk, scowling.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from kw_gate_art import free_slots_in
from kw_bar_art import Canvas
import kw_barhouse, kw_outpost

CAP_X, CAP_Y, W, H = 9, 19, 6, 5
BLACK, BLUE, GREEN, CYAN, RED, MAGENTA, BROWN, LGREY = range(8)
DGREY, LBLUE, LGREEN, LCYAN, LRED, LMAGENTA, YELLOW, WHITE = range(8, 16)


def captive(c, cx, cy, hair_cap, face, shirt, glasses=False):
    """A small seated figure: head (cap/hair + face), a frown, a boxy body."""
    put = c.put
    # head: a 10x10 blob, hair/cap over the top third, face below
    for y in range(-5, 5):
        for x in range(-5, 6):
            if (x / 5.0) ** 2 + (y / 5.0) ** 2 > 1:
                continue
            put(cx + x, cy + y, hair_cap if y < -1 else face)
    if glasses:                              # Mortimer's spectacles
        for x in range(-3, 4):
            put(cx + x, cy, LCYAN)
        put(cx - 2, cy, BLACK); put(cx + 2, cy, BLACK)
    else:                                    # Keen's two cross eyes
        put(cx - 2, cy, BLACK); put(cx + 2, cy, BLACK)
    put(cx - 1, cy + 2, BLACK); put(cx, cy + 2, BLACK); put(cx + 1, cy + 2, BLACK)  # a flat scowl
    # body: a rounded box below the head
    for y in range(6, 18):
        for x in range(-6, 7):
            if abs(x) == 6 and (y < 7 or y > 16):
                continue
            put(cx + x, cy + y, shirt)


def draw():
    c = Canvas(W * 16, H * 16)
    put = c.put
    # The two of them, side by side, sitting up on the bunk (row ~21-22),
    # clear of the console to the left.
    captive(c, 38, 34, GREEN, YELLOW, RED)                   # Keen: green cap
    captive(c, 60, 34, DGREY, LGREY, MAGENTA, glasses=True)  # Mortimer: dark hair, glasses
    # Rope lashed around both, in two bands.
    for band in (44, 50):
        for x in range(30, 68):
            put(x, band, WHITE if x % 4 else BROWN)
            put(x, band + 1, BROWN)
    # Knots where the rope crosses between them.
    for y in range(42, 53):
        put(48, y, BROWN); put(49, y, LGREY)
    # A cross "!" of indignation above them -- they are not happy.
    for y in range(16, 25):
        put(49, y, RED)
    put(49, 27, RED)
    return c.px


def _slots(text):
    import re
    out = set()
    for m in re.finditer(r'\w+Slots\[[^=]*=\s*\{(.*?)\};', text, re.S):
        out |= {int(x) for x in re.findall(r'\d+', m.group(1))}
    return out


def csource(srcdir, d=None):
    d = d or kw_outpost.DATA
    taken = set()
    for f in __import__('glob').glob(os.path.join(srcdir, 'kw_*.h')):
        if os.path.basename(f) != 'kw_captives_art.h':
            taken |= _slots(open(f).read())
    free = [s for s in free_slots_in('4', None, 1, 2915, d=d) if s not in taken]
    px = draw()
    slots = [free[:W * H]]
    lines = ['/* Generated by kwtools/kw_captives_art.py -- do not edit by hand. */',
             '// Keen and Mortimer tied up in the aft bunk, on the Canmore journey.']
    lines += kw_barhouse.header_for('captives', CAP_X, CAP_Y, [px], slots)
    out = os.path.join(srcdir, 'kw_captives_art.h')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out)


def preview(out, d=None):
    from PIL import Image
    img = kw_outpost.to_image(draw())
    img.resize((img.width * 6, img.height * 6), Image.NEAREST).save(out)


if __name__ == '__main__':
    d = sys.argv[3] if len(sys.argv) > 3 else None
    {'preview': preview, 'csource': csource}[sys.argv[1]](sys.argv[2], d)
