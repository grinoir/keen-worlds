"""Keen Worlds' own title, story and ending pictures, for the engine.

    python3 tools/kw_title_art.py art/title omnispeak/src/kw_title_art.h

Reads from the art folder:
  image1.png   the title: the first thing shown when the program is launched
  image2.png   what Keen Worlds' story scrolls over (Keen refuels the ship)
  image3.png   the ending: shown when every world is saved (Keen on the beach)
  asylum_title.png  Address Unknown's title card
  bounty_story.png  Meurglys III's story backdrop
  asylum_story.png  Address Unknown's story backdrop
  epilogue_story.png the final all-worlds-saved story backdrop
Each is cropped to the screen's shape, scaled to 320x200 and written as an
array of 32000 bytes, two pixels a byte (the left one in the high four bits).

The title uses the 16 standard EGA colours, without dithering (the menu
opens over it, in those colours). The other two have colours of their own,
written out beside them for the engine to show while the picture is up: the
ending sixteen, the story picture fifteen - its sixteenth is the colour of
the story's letters.
"""
import sys
from PIL import Image, ImageEnhance

EGA = [0x000000, 0x0000AA, 0x00AA00, 0x00AAAA, 0xAA0000, 0xAA00AA, 0xAA5500, 0xAAAAAA,
       0x555555, 0x5555FF, 0x55FF55, 0x55FFFF, 0xFF5555, 0xFF55FF, 0xFFFF55, 0xFFFFFF]


def screen_shaped(path):
    im = Image.open(path).convert('RGB')
    w, h = im.size
    if w * 200 > h * 320:      # too wide: trim the sides
        nw = h * 320 // 200
        im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    else:                      # too tall: trim top and bottom
        nh = w * 200 // 320
        im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    return im.resize((320, 200), Image.LANCZOS)


def palette_image(colours):
    pal = Image.new('P', (1, 1))
    flat = []
    for r, g, b in colours:
        flat += [r, g, b]
    pal.putpalette(flat + flat[:3] * (256 - len(colours)))
    return pal


def standard(path):
    im = screen_shaped(path)
    # a little more colour, so that yellows and oranges land on the bright
    # EGA colours rather than on brown
    im = ImageEnhance.Brightness(ImageEnhance.Color(im).enhance(1.25)).enhance(1.12)
    return im.quantize(palette=palette_image([(c >> 16, (c >> 8) & 255, c & 255) for c in EGA]), dither=Image.Dither.NONE)


def own_colours(path, count, method, boost=1.0, kmeans=0):
    """The picture in `count` colours of its own (any colours: the engine can
    show others than the EGA's sixteen), with a little dithering. `method`
    is how they are picked: median cut suits a picture of broad, bright
    areas; "maximum coverage" keeps the few strong colours of a dark one
    (the red of the rocket at night)."""
    im = screen_shaped(path)
    # (`boost`: more colour before picking, and `kmeans`: the picked colours
    # settled on the picture's own. A bright daylight picture needs both, or
    # its reds, pinks and greens come out as browns and greys.)
    if boost != 1.0:
        im = ImageEnhance.Color(im).enhance(boost)
    rough = im.quantize(colors=count, method=method, kmeans=kmeans, dither=Image.Dither.NONE).getpalette()[:count * 3]
    colours = [tuple(rough[i * 3:i * 3 + 3]) for i in range(count)]
    return im.quantize(palette=palette_image(colours), dither=Image.Dither.FLOYDSTEINBERG), colours


def write_array(f, name, im):
    px = list(im.getdata())
    data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
    f.write('static const uint8_t %s[32000] = {\n' % name)
    for i in range(0, len(data), 32):
        f.write('\t' + ','.join(str(b) for b in data[i:i + 32]) + ',\n')
    f.write('};\n')


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    folder, out = sys.argv[1:]
    with open(out, 'w') as f:
        f.write('// Keen Worlds: its title, story and ending pictures, 320x200, two pixels a\n'
                '// byte. Generated by tools/kw_title_art.py from art/title - do not edit by hand.\n')
        im = standard('%s/image1.png' % folder)
        write_array(f, 'kw_titlePicture', im)
        im.convert('RGB').resize((640, 400), Image.NEAREST).save('%s/image1_ega.png' % folder)
        # Address Unknown has no title picture of its own.  Keep it in the
        # same standard EGA palette as the episode title cards.
        im = standard('%s/asylum_title.png' % folder)
        write_array(f, 'kw_asylumTitlePicture', im)
        im.convert('RGB').resize((640, 400), Image.NEAREST).save('%s/asylum_title_ega.png' % folder)
        text = (255, 255, 85)
        for name, src, count, method, boost, kmeans in (('kw_story', 'image2.png', 15, Image.Quantize.MAXCOVERAGE, 1.0, 0),
                                                        ('kw_ending', 'image3.png', 16, Image.Quantize.MEDIANCUT, 1.3, 3),
                                                        ('kw_bountyStory', 'bounty_story.png', 15, Image.Quantize.MAXCOVERAGE, 1.0, 0),
                                                        ('kw_asylumStory', 'asylum_story.png', 15, Image.Quantize.MAXCOVERAGE, 1.0, 0),
                                                        ('kw_epilogueStory', 'epilogue_story.png', 15, Image.Quantize.MAXCOVERAGE, 1.0, 0)):
            im, colours = own_colours('%s/%s' % (folder, src), count, method, boost, kmeans)
            write_array(f, name + 'Picture', im)
            f.write('static const uint8_t %sColors[16][3] = {%s};\n' % (name, ', '.join(
                '{%d, %d, %d}' % c for c in (colours + [text])[:16])))
            im.convert('RGB').resize((640, 400), Image.NEAREST).save('%s/%s_ega.png' % (folder, src[:-4]))
    print('wrote', out)


if __name__ == '__main__':
    main()
