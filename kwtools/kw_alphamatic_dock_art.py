"""Generate the Alphamatic map's docking gangway from the Keen 5 gate art.

The Alphamatic v3.0 map has Keen's spawn at (27,121), the shuttle at (32,121),
and open space between the station platform and the shuttle. This overlays the
same kind of lit boarding tube used on Keen 5's map, with its lower row solid
so the short bridge is walkable over space.

    python3 kwtools/kw_alphamatic_dock_art.py csource src/kw_alphamatic_dock_art.h
"""
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import keenmap
import kw_gate_art


def slots_for_map():
    """Choose masked tile slots unused by every Alphamatic map level."""
    import struct

    mod = os.path.abspath(os.path.join(HERE, '..', '..', 'play', 'mods', 'alphamatic'))
    if not os.path.isdir(mod):
        raise RuntimeError('Alphamatic v3.0 files are needed to select its tile slots')
    temp = tempfile.mkdtemp(prefix='kw_alphamatic_dock_')
    aliases = {
        'EGAHEAD.CK5': 'EGAHEAD.CK5', 'EGAGRAPH.CK5': 'EGAGRAPH.CK5',
        'EGADICT.CK5': 'EGADICT.CK5', 'GFXINFOE.CK5': 'GFXINFOE.CK5',
        'GAMEMAPS.CK5': 'GAMEMAPS.CK5', 'MAPHEAD.CK5': 'maphead.ck5',
        'TILEINFO.CK5': 'mytiles.tli',
    }
    for name, source in aliases.items():
        os.symlink(os.path.join(mod, source), os.path.join(temp, name))

    used = set()
    for level in range(100):
        try:
            used.update(keenmap.level(temp, '5', level)[3][1])
        except Exception:
            pass

    info = struct.unpack('<23H', open(os.path.join(temp, 'GFXINFOE.CK5'), 'rb').read()[:46])
    num_tiles16, num_masked = info[2], info[3]
    tile_info = open(os.path.join(temp, 'TILEINFO.CK5'), 'rb').read()
    anim_offset = 2 * num_tiles16 + 4 * num_masked
    anim = lambda tile: struct.unpack('b', tile_info[anim_offset + tile:anim_offset + tile + 1])[0]
    animated_targets = {tile + anim(tile) for tile in range(num_masked) if anim(tile)}

    # Slots can contain original graphics: KW_PlaceArt replaces them in
    # memory. They must be unused by levels and outside animation chains.
    slots = [tile for tile in range(num_masked - 1, -1, -1)
             if tile not in used and tile not in animated_targets]
    if len(slots) < 12:
        raise RuntimeError('not enough unused Alphamatic masked-tile slots')
    return slots[:12]


def csource(out):
    slots = slots_for_map()
    px = kw_gate_art.draw(0)
    lines = [
        '/* Generated by kwtools/kw_alphamatic_dock_art.py -- do not edit by hand. */',
        '#define KW_AL_DOCK_TILES_W 4',
        '#define KW_AL_DOCK_TILES_H 3',
        'static const uint16_t kw_alDockSlots[1][KW_AL_DOCK_TILES_H][KW_AL_DOCK_TILES_W] = {',
        '\t{',
    ]
    for row in range(3):
        lines.append('\t\t{' + ', '.join(str(slots[row * 4 + col]) for col in range(4)) + '},')
    lines += [
        '\t},',
        '};',
        '',
        'static const uint8_t kw_alDockTiles[1][KW_AL_DOCK_TILES_H][KW_AL_DOCK_TILES_W][160] = {',
        '\t{',
    ]
    for row in range(3):
        lines.append('\t\t{')
        for col in range(4):
            if col == 3:
                data = bytes([0xff] * 32 + [0] * 128)
            else:
                data = kw_gate_art.tile_bytes(px, col, row)
            lines.append('\t\t\t{' + ','.join('0x%02x' % b for b in data) + '},')
        lines.append('\t\t},')
    lines += ['\t},', '};', '']
    with open(out, 'w') as output:
        output.write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    if len(sys.argv) != 3 or sys.argv[1] != 'csource':
        raise SystemExit(__doc__)
    csource(sys.argv[2])
