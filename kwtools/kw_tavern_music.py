"""Write the tavern's tune (Border Village) as AdLib music for Keen Worlds.

An original jig in G major, 6/8: a reedy squeezebox plays the tune over a
plucked bass and off-beat chords. The output is an IMF stream (OPL2 register,
value, 16-bit delay in 1/560 s ticks), the format of the games' own music,
compiled into the engine so nobody's AUDIO file is touched.

Usage: python3 tools/kw_tavern_music.py csource > omnispeak/src/kw_tavern_music.h
"""
import sys

EIGHTH = 100  # ticks: dotted quarter = 107 bpm
GAP = 12      # silence before a note is struck again

FNUM = {'C': 0x157, 'C#': 0x16B, 'D': 0x181, 'D#': 0x198, 'E': 0x1B0, 'F': 0x1CA,
        'F#': 0x1E5, 'G': 0x202, 'G#': 0x220, 'A': 0x241, 'A#': 0x263, 'B': 0x287}

# One bar per line, six eighths; '-' holds the note, '.' is a rest.
TUNE = """
B4 D5 B4 G4 B4 D5
G5 -  D5 B4 -  G4
E5 G5 E5 C5 E5 G5
F#5 - D5 A4 -  D5
B4 D5 B4 G4 B4 D5
G5 -  E5 B4 -  E5
C5 E5 C5 A4 D5 F#5
G5 -  -  G4 -  -
E5 G5 B5 G5 E5 B4
C5 E5 G5 E5 -  C5
D5 G5 B5 G5 D5 B4
A4 D5 F#5 A5 - F#5
G5 B5 G5 E5 G5 E5
C5 E5 G5 E5 C5 E5
D5 F#5 A5 F#5 D5 A4
G4 B4 D5 G5 -  -
"""
# Two chords per bar (one per beat).
CHORDS = "G G  G G  C C  D D  G G  Em Em  C D  G G  Em Em  C C  G G  D D  Em Em  C C  D D  G G".split()
# chord: bass note, the two notes of the off-beat stab
CHORD = {'G': ('G2', 'B3', 'D4'), 'C': ('C3', 'C4', 'E4'), 'D': ('D3', 'A3', 'F#4'), 'Em': ('E3', 'G3', 'B3')}

# OPL2 voices: (modulator, carrier) register values
#            tremolo/sustain/mult  level        attack/decay  sustain/release  feedback
VOICES = [
    ((0x21, 0x21), (0x1C, 0x04), (0x72, 0x82), (0x35, 0x26), 0x08),  # 0 squeezebox
    ((0x01, 0x01), (0x12, 0x06), (0xF3, 0xF4), (0x58, 0x77), 0x06),  # 1 plucked bass
    ((0x01, 0x01), (0x1A, 0x12), (0xF4, 0xF5), (0x77, 0x77), 0x04),  # 2 chord
    ((0x01, 0x01), (0x1A, 0x12), (0xF4, 0xF5), (0x77, 0x77), 0x04),  # 3 chord
]
# Channel 0 belongs to the games' AdLib sound effects, so the voices use 1-4.
FIRST = 1
OPS = [(0x01, 0x04), (0x02, 0x05), (0x08, 0x0B), (0x09, 0x0C)]  # operator offsets of channels 1-4


def pitch(note):
    return int(note[-1]), FNUM[note[:-1]]


def build():
    ev = []  # (time, order, reg, value)

    def on(t, ch, note):
        block, f = pitch(note)
        ch += FIRST
        ev.append((t, 1, 0xA0 + ch, f & 0xFF))
        ev.append((t, 2, 0xB0 + ch, 0x20 | block << 2 | f >> 8))

    def off(t, ch):
        ev.append((t, 0, 0xB0 + FIRST + ch, 0))

    for ch, (mult, level, ad, sr, fb) in enumerate(VOICES):
        for base, vals in ((0x20, mult), (0x40, level), (0x60, ad), (0x80, sr)):
            for op, v in zip(OPS[ch], vals):
                ev.append((0, -2, base + op, v))
        ev.append((0, -2, 0xC0 + FIRST + ch, fb))
        off(0, ch)

    notes = TUNE.split()
    assert len(notes) == 96 and len(CHORDS) == 32
    for i, n in enumerate(notes):
        if n in '-.':
            continue
        length = 1
        while i + length < len(notes) and notes[i + length] == '-':
            length += 1
        on(i * EIGHTH, 0, n)
        off((i + length) * EIGHTH - GAP, 0)
    for beat, name in enumerate(CHORDS):
        t = beat * 3 * EIGHTH
        bass, a, b = CHORD[name]
        on(t, 1, bass)
        off(t + 2 * EIGHTH, 1)
        on(t + 2 * EIGHTH, 2, a)
        on(t + 2 * EIGHTH, 3, b)
        off(t + 3 * EIGHTH - GAP, 2)
        off(t + 3 * EIGHTH - GAP, 3)
    end = len(notes) * EIGHTH
    ev.append((end, 9, 0xB0 + FIRST, 0))  # the loop point: the player restarts after its last event
    ev.sort()
    out = bytearray()
    for k, (t, _, reg, val) in enumerate(ev):
        delay = ev[k + 1][0] - t if k + 1 < len(ev) else 0
        out += bytes((reg, val, delay & 0xFF, delay >> 8))
    return bytes(out)


if __name__ == '__main__':
    data = build()
    if sys.argv[1:] != ['csource']:
        sys.exit(__doc__)
    print('// Generated by tools/kw_tavern_music.py - do not edit by hand.')
    print('static const uint8_t kw_tavernMusic[%d] = {' % len(data))
    for i in range(0, len(data), 16):
        print('\t' + ' '.join('0x%02x,' % b for b in data[i:i + 16]))
    print('};')
