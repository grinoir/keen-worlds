"""The creator's portrait in Border Village's house (Keen Worlds art).

    python3 tools/kw_portrait_art.py preview OUT.png   # framed, in the room
    python3 tools/kw_portrait_art.py csource OUT.h     # C data for the engine

The source photo (assets/creator-portrait-source.jpg) is cropped, converted to
EGA greys with patterned (Bayer) dithering and put in a gilded frame on a
48x64 canvas covering map tiles 65-67 x 27-30 of Keen 4 level 1: the back
wall of the tavern room, just inside its door (see tools/kw_barhouse.py).
"""
import os, sys
from PIL import Image, ImageEnhance, ImageFilter

HERE = os.path.dirname(__file__)
sys.path.insert(0, HERE)
from kw_gate_art import EGA, tile_bytes, free_slots_in

SOURCE = os.path.join(HERE, '..', 'assets', 'creator-portrait-source.jpg')
W, H = 48, 64
ORIGIN = (65, 27)
SLOT_RANGE = (1, 299)   # Keen 4 tile slots reserved for this art
EPISODE, LEVEL = '4', 1

BLACK, BROWN, LGREY, DGREY, YELLOW, WHITE = 0, 6, 7, 8, 14, 15
GREYS = [BLACK, DGREY, LGREY, WHITE]
T = None

# The photo area inside the frame.
PX0, PY0, PW, PH = 7, 12, 34, 43
# Crop of the source photo (left, top, right, bottom): hat, face and folded
# arms, at the photo area's aspect ratio. Then the tone settings that keep the
# hat's silhouette and the lit face readable at this size.
CROP = (220, 110, 451, 410)
BLUR, BRIGHTNESS, CONTRAST, GAMMA = 1.2, 1.5, 2.2, 0.8
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def photo_pixels():
    img = Image.open(SOURCE).convert('L').crop(CROP).filter(ImageFilter.GaussianBlur(BLUR))
    img = ImageEnhance.Brightness(img).enhance(BRIGHTNESS)
    img = ImageEnhance.Contrast(img).enhance(CONTRAST)
    img = img.resize((PW, PH), Image.LANCZOS)
    out = [[0] * PW for _ in range(PH)]
    for y in range(PH):
        for x in range(PW):
            v = 255 * (img.getpixel((x, y)) / 255) ** GAMMA
            v += ((BAYER[y % 4][x % 4] + 0.5) / 16 - 0.5) * 85   # ordered dither
            out[y][x] = GREYS[max(0, min(3, int(round(v / 85))))]
    return out


def draw(frame=0):
    px = [[T] * W for _ in range(H)]

    def put(x, y, c):
        if 0 <= x < W and 0 <= y < H:
            px[y][x] = c

    def rect(x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                put(x, y, c)

    # Hanging wire and nail. The frame leaves room above and below, so it
    # clears the ceiling and the floor.
    put(23, 2, LGREY); put(24, 2, LGREY)
    put(23, 3, DGREY); put(24, 3, DGREY)
    for i in range(4):
        put(22 - i, 4 + i, BLACK)
        put(25 + i, 4 + i, BLACK)

    # Gilded frame: dark outline, gold with lit top-left edges, a dark inner
    # bevel, and corner studs.
    rect(4, 8, 43, 58, BLACK)
    rect(5, 9, 42, 57, BROWN)
    rect(5, 9, 42, 9, YELLOW)
    rect(5, 9, 5, 57, YELLOW)
    rect(6, 11, 41, 55, BLACK)
    for (x, y) in ((6, 10), (41, 10), (6, 56), (41, 56)):
        put(x, y, YELLOW)

    pic = photo_pixels()
    for y in range(PH):
        for x in range(PW):
            put(PX0 + x, PY0 + y, pic[y][x])
    return px


def to_image(px):
    img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    for y in range(H):
        for x in range(W):
            if px[y][x] is not None:
                img.putpixel((x, y), EGA[px[y][x]] + (255,))
    return img


def preview(out):
    import keenmap, keenrender
    d = os.path.join(HERE, '..', 'play')
    name, w, h, (bg, fg, info) = keenmap.level(d, EPISODE, LEVEL)
    g = keenrender.Graphics(d, EPISODE)
    x0, y0, x1, y1 = 56, 24, 84, 34
    img = Image.new('RGBA', ((x1 - x0) * 16, (y1 - y0) * 16), (0, 0, 0, 255))
    for y in range(y0, y1):
        for x in range(x0, x1):
            t = g.tile(bg[y * w + x], False)
            if t: img.paste(t, ((x - x0) * 16, (y - y0) * 16))
            if fg[y * w + x]:
                t = g.tile(fg[y * w + x], True)
                if t: img.alpha_composite(t, ((x - x0) * 16, (y - y0) * 16))
    img.alpha_composite(to_image(draw()), ((ORIGIN[0] - x0) * 16, (ORIGIN[1] - y0) * 16))
    big = img.convert('RGB').resize((img.width * 4, img.height * 4), Image.NEAREST)
    big.save(out)
    print('wrote', out)


def csource(out):
    cells = (W // 16) * (H // 16)
    slots = free_slots_in(EPISODE, cells, *SLOT_RANGE)
    px = draw()
    lines = ['/* Generated by tools/kw_portrait_art.py -- do not edit by hand. */',
             '#define KW_PORTRAIT_TILES_W %d' % (W // 16),
             '#define KW_PORTRAIT_TILES_H %d' % (H // 16),
             '#define KW_PORTRAIT_ORIGIN_X %d' % ORIGIN[0],
             '#define KW_PORTRAIT_ORIGIN_Y %d' % ORIGIN[1],
             '// Empty, unused Keen 4 masked-tile slots that hold the art: [frame][row][column].',
             'static const uint16_t kw_portraitSlots[1][KW_PORTRAIT_TILES_H][KW_PORTRAIT_TILES_W] = {',
             '\t{' + ', '.join('{' + ', '.join(str(slots[ty * (W // 16) + tx]) for tx in range(W // 16)) + '}'
                             for ty in range(H // 16)) + '},',
             '};',
             '// [frame][row][column][mask + 4 planes]',
             'static const uint8_t kw_portraitTiles[1][KW_PORTRAIT_TILES_H][KW_PORTRAIT_TILES_W][160] = {',
             '\t{']
    for ty in range(H // 16):
        lines.append('\t\t{')
        for tx in range(W // 16):
            lines.append('\t\t\t{' + ','.join('0x%02x' % v for v in tile_bytes(px, tx, ty)) + '},')
        lines.append('\t\t},')
    lines += ['\t},', '};']
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out)


if __name__ == '__main__':
    {'preview': preview, 'csource': csource}[sys.argv[1]](sys.argv[2])
