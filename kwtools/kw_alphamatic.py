"""Convert the player's The Alphamatic 3.0 archive for native Keen Worlds.

Usage: python3 kwtools/kw_alphamatic.py MOD_FOLDER KEEN5E.EXE OUTPUT_FOLDER
Only reads the original Keen 5 v1.4 executable as data; never runs DOS code.
"""
from pathlib import Path
import contextlib
import hashlib
import io
import re
import shutil
import struct
import sys

from kw_accumulators import cstring, escape
from kw_patconv import Game, parse_pat, cmd_actions, cmd_check

PATCH_SHA256 = '5ce108ab10fca7f5f7d3f348dbe62f335a7949cccf0c2d78c171aa87c90a0042'
STAND_INS = ['AL_LightningThink=037D:032C', 'AL_FuseThink=CK5_SpirogripSpin',
             'AL_FuseCol=11C4:0B61', 'AL_ImpactCol=CK5_MineShrapCol']
SETTINGS = '''
%string ca_mapHead "maphead.ck5"
%string ca_tileInfo "mytiles.tli"
%string ca_audioHead "AUDIOHED.CK5"
%int ca_audioUncompressed 2
%int ca_audStartMusic 173
%int ca_audNumSongs 33
%int ck5_mapElevators 0
%int CK_MapTeleDoneTile1 0x0A9E
%int CK_MapPreserveCoordinates 1
%int CK5_ElevatorFullCoordinates 1
%int CK5_ElevatorCloseDestination 1
%int CK5_MapMarsMinY 124
%int CK5_SliceInvincible 1
%int ck_maxLevel 25
%int ck_maxEnterLevel 25
%int ck_maxDoneLevel 25
%int CK_NumMusicLevels 30
%int CK_EndingMusicLevel 26
%int CK_StarWarsMusicLevel 27
%int CK_HelpMusicLevel 28
%int CK_GameOverMusicLevel 29
%string ck_str_exitToMap "Exit to Alphamatic"
%string ck5_str_korath3 "Keen is marooned\\non Mars Station"
%string ck5_str_fuseDestroyedKorath "That should enable\\nthe 1st elevator\\n"
%string ck_str_levelWarp "  Warp to which level(1-25):"
'''


def convert(folder, exe, output):
    folder, output = Path(folder), Path(output)
    base = Path(__file__).resolve().parents[1]/'data/keen5'
    files = {p.name.lower(): p for p in folder.iterdir() if p.is_file()}
    if hashlib.sha256(files['patch5.pat'].read_bytes()).hexdigest() != PATCH_SHA256:
        raise ValueError('The Alphamatic port requires the audited version 3.0 patch.')
    g = Game(str(exe), str(base))
    g.stand_ins(STAND_INS)
    pats = parse_pat(files['patch5.pat'])
    image = g.patched(pats)
    lines = ['# The Alphamatic 3.0, by Gridlock. Native code: src/kw_alphamatic.c.',
             '# Generated by kwtools/kw_alphamatic.py from the player\'s download.', SETTINGS]
    for name, table in [('ck_str_levelNames',0x31AB4), ('ck_str_levelEntryText',0x35EC4)]:
        texts = []
        for i in range(26):
            ptr = struct.unpack_from('<I',image,table+4*i)[0]
            texts.append(cstring(image,(ptr>>16)*16+(ptr&65535)))
        lines.append('%stringarray '+name+'\n'+',\n'.join('"'+escape(t)+'"' for t in texts))
    story = files['story.ck5'].read_bytes().split(b'\0')[0].decode('latin1')
    lines.append('%string ck_str_storyText "'+escape(story)+'"')
    music = list(struct.unpack_from('<26H',image,0x3067A)) + [14,23,20,23]
    lines.append('%intarray CK_LevelMusic '+', '.join(map(str,music)))
    lines.append('%override "EPISODE.CK5"')
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        cmd_actions(g,pats)
    if '?' in buf.getvalue():
        raise ValueError('Unmapped patched action: '+buf.getvalue())
    lines.append(buf.getvalue())
    output.mkdir(parents=True,exist_ok=True)
    mod = output/'ALPHAM.CK5'
    mod.write_text('\n\n'.join(lines)+'\n',encoding='latin1')
    assert cmd_check(g,pats,str(mod)) == 0
    for name in ['AUDIO.CK5','AUDIOHED.CK5','EGAGRAPH.CK5','EGAHEAD.CK5',
                 'GAMEMAPS.CK5','maphead.ck5','mytiles.tli','Readme.txt','Patch5.pat']:
        shutil.copy2(files[name.lower()],output/name)
    for name in ['EGADICT.CK5','GFXINFOE.CK5','AUDINFOE.CK5']:
        shutil.copy2(base/name,output/name)
    # The graphics dictionary is unchanged by this patch, checked against
    # the player's original EXE rather than assuming an arbitrary release.
    dictionary = (base/'EGADICT.CK5').read_bytes()
    assert g.img.find(dictionary) >= 0
    print('The Alphamatic native data installed in',output)


if __name__ == '__main__':
    if len(sys.argv) != 4: sys.exit(__doc__)
    convert(*sys.argv[1:])
