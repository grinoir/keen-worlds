"""Keen asleep in the Megarocket's bunk (Keen Worlds): on Craig's own worlds
(Aurora, Canmore, Revival-as-Craig) you play Craig, and Keen is the one aboard
the ship. Here he is dozing in the aft bunk -- so Craig can't use it to drop
into Keen Dreams. Drawn over the cabin's own bunk art (kw_shiproom_art.py).

    python3 kwtools/kw_keenbunk_art.py preview OUT.png
    python3 kwtools/kw_keenbunk_art.py csource SRCDIR

A piece over the aft bunk (cabin map tiles 9-14, rows 21-23). The bunk's red
blanket and white pillow are already there; this adds Keen's head on the pillow,
a lump under the blanket, and a drowsy "z z z".
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from kw_gate_art import free_slots_in
from kw_bar_art import Canvas
import kw_barhouse, kw_outpost

BUNK_X, BUNK_Y, W, H = 9, 19, 6, 5
BLACK, BLUE, GREEN, CYAN, RED, MAGENTA, BROWN, LGREY = range(8)
DGREY, LBLUE, LGREEN, LCYAN, LRED, LMAGENTA, YELLOW, WHITE = range(8, 16)


def draw():
    c = Canvas(W * 16, H * 16)
    put = c.put

    # A gentle bump in the red blanket, to the right of the pillow: Keen's
    # body under the covers (the blanket itself is the cabin's own art, along
    # tiles 11.5-14 = x 40-80, row 22 = y 48).
    for x in range(40, 78):
        h = int(3 * (1 - ((x - 55) / 20.0) ** 2))
        for y in range(48 - h, 49):
            put(x, y, LRED if y == 48 - h else RED)

    # Keen's head, resting on the pillow (left end of the bunk, ~tile 11, row 22).
    cx, cy = 37, 44                       # centre of the head
    for y in range(-6, 7):
        for x in range(-7, 8):
            if (x / 7.0) ** 2 + (y / 6.0) ** 2 > 1:
                continue
            if y < -1:                    # the green cap
                put(cx + x, cy + y, LGREEN if y < -4 else GREEN)
            else:                         # the face
                put(cx + x, cy + y, YELLOW)
    # a blonde tuft at the back, a closed eye, a calm mouth
    put(cx - 7, cy - 1, YELLOW); put(cx - 7, cy, YELLOW); put(cx - 6, cy + 1, YELLOW)
    for x in range(1, 5):
        put(cx + x, cy + 1, BLACK)        # the shut eye
    put(cx + 2, cy + 4, BROWN); put(cx + 3, cy + 4, BROWN)
    # the cap's brim, out over the face a touch
    put(cx + 5, cy - 1, GREEN); put(cx + 6, cy - 2, GREEN)

    # A drowsy "z z z", rising up from the head, clear of the hanging lamp.
    def zed(ox, oy, s):
        for i in range(s):
            put(ox + i, oy, WHITE)                    # top bar
            put(ox + s - 1 - i, oy + i, WHITE)        # diagonal
            put(ox + i, oy + s - 1, WHITE)            # bottom bar
    zed(40, 30, 4); zed(46, 20, 5); zed(53, 8, 6)
    return c.px


def _slots(text):
    import re
    out = set()
    for m in re.finditer(r'\w+Slots\[[^=]*=\s*\{(.*?)\};', text, re.S):
        out |= {int(x) for x in re.findall(r'\d+', m.group(1))}
    return out


def csource(srcdir, d=None):
    d = d or kw_outpost.DATA
    taken = set()
    for f in __import__('glob').glob(os.path.join(srcdir, 'kw_*.h')):
        if os.path.basename(f) != 'kw_keenbunk_art.h':
            taken |= _slots(open(f).read())
    free = [s for s in free_slots_in('4', None, 1, 2915, d=d) if s not in taken]
    px = draw()
    slots = [free[:W * H]]
    lines = ['/* Generated by kwtools/kw_keenbunk_art.py -- do not edit by hand. */',
             '// Keen dozing in the Megarocket\'s aft bunk, on Craig\'s worlds.']
    lines += kw_barhouse.header_for('keenbunk', BUNK_X, BUNK_Y, [px], slots)
    out = os.path.join(srcdir, 'kw_keenbunk_art.h')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out)


def preview(out, d=None):
    from PIL import Image
    img = kw_outpost.to_image(draw())
    img.resize((img.width * 6, img.height * 6), Image.NEAREST).save(out)


if __name__ == '__main__':
    d = sys.argv[3] if len(sys.argv) > 3 else None
    {'preview': preview, 'csource': csource}[sys.argv[1]](sys.argv[2], d)
