"""Convert the player's Marooned on Mars - Galaxy files for the native arcade.

Usage: python3 kwtools/kw_mars.py MOD_FOLDER KEEN5E.EXE OUTPUT_FOLDER

The executable is read as data only. Actions come from the mod's patched
Keen 5 v1.4 tables; kw_mars.c implements the changes to their functions.
No DOS executable is run. The source ZIP and original game are left intact.
"""
from pathlib import Path
import argparse
import contextlib
import io
import hashlib
import re
import shutil
import struct

from kw_patconv import Game, parse_pat, cmd_actions, cmd_check
from kw_accumulators import cstring, escape

PATCH_SHA256 = 'c563c5638e6f04c80a9a39d9b7a74f4d3e7ab97f0c8e750dc0204e7f56f4ee65'

STAND_INS = [
    'MARS_MineSound=CK5_MineMove',
    'MARS_Collect=CK5_MineShrapCol',
    'MARS_RockCol=CK5_VolteCol',
    'MARS_AmptonCol=CK5_AmptonCol',
    'MARS_RoboCol=CK5_RoboCol',
    'MARS_YorpCol=037D:0520',
    'MARS_YorpStunCol=037D:0590',
    'MARS_YorpStunThink=037D:059D',
    'MARS_YorpLand=CK5_SpirogripSpin',
    'MARS_CommanderCol=11C4:0CDB',
    'MARS_StatueCol=0AAF:1FB7',
    'MARS_IceCol=CK_TurretShotCol',
    'MARS_ShellyCol=CK5_ShellyCol',
    'MARS_ShellyWait=CK5_ShellyWait',
]

SETTINGS = '''
%int MARS_Active 1
%string ca_mapFile "editmaps.ck5"
%string ca_mapHead "maphead.ck5"
%string ca_tileInfo "Keen5.tli"
%string ca_audioHead "AUDIOHED.CK5"
%int ca_audioUncompressed 2
%int ck5_mapElevators 0
%int CK_MapTeleDoneTile1 0x0A8F
%int CK5_QEDEveryLevel 1
%int ck_maxLevel 17
%int ck_maxEnterLevel 24
%int ck_maxDoneLevel 24
%int CK5_AmptonSpawnYOffset -672
%int CK5_AmptonSilent 1
%int CK5_AmptonFlashes 1
%int CK5_SpirogripSpawnYOffset -273
%int CK5_RoboSpawnYOffset -273
%int CK5_RoboNumShots 1
%int CK5_RoboShotLeftXOffset 0
%int CK5_RoboShotRightXOffset 208
%int CK5_RoboShotYOffset 80
%int CK5_RoboShotYVelocity 0
%int CK5_RoboShotRecoil 0
%int CK5_MasterSpawnYOffset 0
%int CK5_ShocksundHealth 99
%int CK5_ShocksundStandChance 0
%int CK5_ShocksundShotYOffset -48
%int SOUND_GOTCENTILIFE 17
%string ck_str_exitToMap "Exit to Mars"
%string ck_str_statusCentilives "PARTS"
%string ck5_str_statusKeycard "ITEMS"
%intarray ck_terminatorPalette1 0, 2, 2, 18, 1, 1, 1, 1, 17, 17, 17, 17, 19, 19, 19, 19, 0
%intarray ck_terminatorPalette2 0, 2, 2, 18, 1, 1, 1, 1, 17, 17, 17, 17, 19, 19, 19, 2, 0
'''


def convert(game, exe, out):
    game, out = Path(game), Path(out)
    base = Path(__file__).resolve().parents[1] / 'data/keen5'
    files = {p.name.lower(): p for p in game.iterdir() if p.is_file()}
    if hashlib.sha256(files['pat.pat'].read_bytes()).hexdigest() != PATCH_SHA256:
        raise ValueError('This port supports the K1n9_Duk3-fixed 2020-09-21 patch revision; this patch needs a fresh compatibility review.')
    g = Game(str(exe), str(base))
    g.stand_ins(STAND_INS)
    pats = parse_pat(files['pat.pat'])
    patched = g.patched(pats)
    lines = ['# Marooned on Mars - Galaxy: Dr. Colossus; fixes by K1n9_Duk3.',
             '# Native arcade conversion, generated by kwtools/kw_mars.py.',
             '# The matching gameplay functions are in src/kw_mars.c.', SETTINGS]
    for name, table in [('ck_str_levelNames', 0x31AB4), ('ck_str_levelEntryText', 0x31B18)]:
        texts = []
        for i in range(18):
            ptr = struct.unpack_from('<I', patched, table + 4*i)[0]
            texts.append(cstring(patched, (ptr >> 16)*16 + (ptr & 0xffff)))
        lines.append('%stringarray ' + name + '\n' + ',\n'.join('"'+escape(s)+'"' for s in texts))
    lines.append('%string ck_str_storyText "'+escape(cstring(patched, 0x1FDE0))+'"')
    # The patch extends the lookup count to 24; only the first 20 words are
    # songs. The bytes after that are text, so never use them as song IDs.
    music = list(struct.unpack_from('<20H', patched, 0x3067A)) + [0]*4
    lines.append('%intarray CK_LevelMusic ' + ', '.join(map(str, music)))
    # Cache boundaries are tables of 38 shorts in the data segment.
    # Omnispeak's cache ordering differs from the DOS program's. Match
    # each original (start,end) pair, then take its patched pair.
    gfx = (base/'GFXCHUNK.CK5').read_text()
    native = []
    for name in ['lumpStarts', 'lumpEnds']:
        block = gfx.split('%intarray '+name)[1].split('%')[0]
        native.append([g.ints[v] for v in re.findall(r'@(\w+)', block)])
    old = [struct.unpack_from('<38H', g.img, at) for at in [0x31A0C,0x31A60]]
    new = [struct.unpack_from('<38H', patched, at) for at in [0x31A0C,0x31A60]]
    pairs = list(zip(*old))
    for i,pair in enumerate(zip(*native)):
        if pair in pairs:
            j=pairs.index(pair)
            native[0][i],native[1][i]=new[0][j],new[1][j]
    for name,vals in zip(['lumpStarts','lumpEnds'],native):
        lines.append('%intarray '+name+' '+', '.join(map(str, vals)))
    lines.append('%override "EPISODE.CK5"')
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        cmd_actions(g, pats)
    actions = buf.getvalue()
    if '?' in actions:
        raise ValueError('Unmapped action function or next action:\n'+actions)
    lines.append(actions)
    lines += ['%action CK5_ACT_SpirogripSpawn = CK5_ACT_SpirogripSpin8',
              '%action CK5_ACT_RoboShootDone = CK5_ACT_SpirogripSpin8',
              '%action CK5_ACT_ShocksundJumpStart = CK5_ACT_ShocksundShoot0']
    out.mkdir(parents=True, exist_ok=True)
    mod = out / 'MARS.CK5'
    mod.write_text('\n\n'.join(lines)+'\n', encoding='latin1')
    assert cmd_check(g, pats, str(mod)) == 0
    for name in ['AUDIO.CK5', 'AUDIODCT.CK5', 'AUDIOHED.CK5', 'EGADICT.CK5',
                 'EGAGRAPH.CK5', 'EGAHEAD.CK5', 'editmaps.ck5', 'maphead.ck5', 'Keen5.tli', 'changelog.txt']:
        shutil.copy2(files[name.lower()], out/name)
    print('Native Mars data installed in', out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game'); parser.add_argument('exe'); parser.add_argument('out')
    a = parser.parse_args()
    convert(a.game, a.exe, a.out)
