"""Vorta Cola on the Megarocket's navigation screen (Keen Worlds): while the
ship stands on Aurora Bliss and that world isn't saved, Craig's spill is on
the Navi-Com in the cabin, and the ship can't take off.

    python3 kwtools/kw_cola_art.py preview OUT.png [GAMEDIR]
    python3 kwtools/kw_cola_art.py csource SRCDIR [GAMEDIR]

A 4x3-tile piece over the navigation screen (cabin map tiles 7-10, rows
6-8), drawn over the cabin's own art (kw_shiproom_art.py).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from kw_gate_art import free_slots_in
from kw_bar_art import Canvas
import kw_barhouse, kw_outpost

COLA_X, COLA_Y, W, H = 7, 6, 4, 3
BLACK, BLUE, GREEN, CYAN, RED, MAGENTA, BROWN, LGREY = range(8)
DGREY, LBLUE, LGREEN, LCYAN, LRED, LMAGENTA, YELLOW, WHITE = range(8, 16)


def draw():
    c = Canvas(W * 16, H * 16)
    DX, DY = 6, 14   # (onto the radar screen itself, measured in the cabin)
    put = lambda x, y, col: c.put(x + DX, y + DY, col)
    # smears across the radar screen (in this piece: about x 18-46, y 8-30)
    blobs = [(26, 14, 6, 3), (37, 18, 6, 3), (30, 24, 4, 2), (43, 12, 3, 2), (22, 21, 3, 2)]
    for cx, cy, rx, ry in blobs:
        for y in range(cy - ry, cy + ry + 1):
            for x in range(cx - rx, cx + rx + 1):
                if ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1:
                    put(x, y, BROWN)
    # drips running down from them, each ending in a drop
    for x, top, length in ((24, 16, 10), (33, 20, 14), (40, 20, 8), (29, 25, 9), (44, 13, 6)):
        end = min(top + length, H * 16 - 2 - DY)
        for y in range(top, end):
            put(x, y, BROWN)
        put(x, end, BROWN); put(x + 1, end, BROWN); put(x, end + 1, BROWN)
    # the shine of something sticky
    for x, y in ((24, 13), (25, 13), (35, 17), (36, 17), (29, 23), (42, 11)):
        put(x, y, YELLOW)
    return c.px


def _slots(text):
    import re
    out = set()
    for m in re.finditer(r'\w+Slots\[[^=]*=\s*\{(.*?)\};', text, re.S):
        out |= {int(x) for x in re.findall(r'\d+', m.group(1))}
    return out


def csource(srcdir, d=None):
    d = d or kw_outpost.DATA
    # (every other header's slots; not this one's own, when it is made again)
    taken = set()
    for f in __import__('glob').glob(os.path.join(srcdir, 'kw_*.h')):
        if os.path.basename(f) != 'kw_cola_art.h':
            taken |= _slots(open(f).read())
    free = [s for s in free_slots_in('4', None, 1, 2915, d=d) if s not in taken]
    px = draw()
    slots = [free[:W * H]]
    lines = ['/* Generated by kwtools/kw_cola_art.py -- do not edit by hand. */',
             '// Vorta Cola on the Navi-Com, in the Megarocket\'s cabin (while it stands',
             '// on Aurora Bliss and that world isn\'t saved).']
    lines += kw_barhouse.header_for('cola', COLA_X, COLA_Y, [px], slots)
    out = os.path.join(srcdir, 'kw_cola_art.h')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('wrote', out)


def preview(out, d=None):
    from PIL import Image
    img = kw_outpost.to_image(draw())
    img.resize((img.width * 6, img.height * 6), Image.NEAREST).save(out)


if __name__ == '__main__':
    d = sys.argv[3] if len(sys.argv) > 3 else None
    {'preview': preview, 'csource': csource}[sys.argv[1]](sys.argv[2], d)
